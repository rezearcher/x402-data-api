#!/usr/bin/env python3
"""Refresh the vendored malicious-EVM-address snapshot (scam / phishing / drainer).

Closes the companion gap to the OFAC screen: a counterparty can be perfectly
un-sanctioned and still be a known wallet-drainer or phishing collector. This
pulls two keyless, actively-maintained, reputable community threat-intel lists
and writes a TypeScript data module the Worker reads at request time:

  * ScamSniffer scam-database (blacklist/address.json) — the crypto drainer /
    phishing address feed used by wallets (Rabby et al). Flat lowercase array.
  * MyEtherWallet ethereum-lists (addresses-darklist.json) — curated phishing /
    scam collector addresses with per-entry comments.

Merged, lowercased, de-duped. Keyless, no deps beyond urllib. The vendored
snapshot means the live route has NO runtime network dependency — it degrades
open and is fast. Claims Law: a non-match is "not listed", never "safe".

Run: python3 -I scripts/refresh_malicious_list.py
"""
import json, re, sys, urllib.request, datetime

SCAMSNIFFER = "https://raw.githubusercontent.com/scamsniffer/scam-database/main/blacklist/address.json"
MEW_DARKLIST = "https://raw.githubusercontent.com/MyEtherWallet/ethereum-lists/master/src/addresses/addresses-darklist.json"
OUT = "src/data/malicious_addresses.ts"
ADDR_RE = re.compile(r"^0x[0-9a-fA-F]{40}$")


def _fetch(url: str):
    req = urllib.request.Request(url, headers={"User-Agent": "greyridge-malicious-refresh"})
    with urllib.request.urlopen(req, timeout=40) as r:
        return json.load(r)


def main() -> int:
    addrs: set[str] = set()

    # ScamSniffer: flat array of lowercase 0x addresses.
    ss_count = 0
    try:
        raw = _fetch(SCAMSNIFFER)
        for a in raw:
            if isinstance(a, str) and ADDR_RE.match(a):
                addrs.add(a.lower())
                ss_count += 1
    except Exception as e:  # noqa: BLE001
        print(f"refused: ScamSniffer fetch failed: {e}", file=sys.stderr)
        return 1

    # MEW darklist: array of {address, comment, date}.
    mew_count = 0
    try:
        raw = _fetch(MEW_DARKLIST)
        for row in raw:
            a = row.get("address") if isinstance(row, dict) else None
            if isinstance(a, str) and ADDR_RE.match(a):
                addrs.add(a.lower())
                mew_count += 1
    except Exception as e:  # noqa: BLE001
        print(f"refused: MEW darklist fetch failed: {e}", file=sys.stderr)
        return 1

    merged = sorted(addrs)
    if len(merged) < 1000:
        print(f"refused: merged list too small ({len(merged)}) — upstream likely degraded", file=sys.stderr)
        return 1

    today = datetime.date.today().isoformat()
    lines = [
        "// GENERATED by scripts/refresh_malicious_list.py — do not edit by hand.",
        "// Keyless, actively-maintained community threat-intel on malicious EVM",
        "// addresses (scam / phishing / wallet-drainer collectors), merged + deduped:",
        "//   * ScamSniffer scam-database (blacklist/address.json)",
        "//   * MyEtherWallet ethereum-lists (addresses-darklist.json)",
        f"// Snapshot: {today} · {len(merged)} unique EVM addresses"
        f" (scamsniffer={ss_count}, mew_darklist={mew_count}).",
        f'export const MALICIOUS_SNAPSHOT_DATE = "{today}";',
        f"export const MALICIOUS_SCAMSNIFFER_URL = {json.dumps(SCAMSNIFFER)};",
        f"export const MALICIOUS_MEW_URL = {json.dumps(MEW_DARKLIST)};",
        "// Lowercased 0x EVM addresses on community scam/phishing/drainer lists.",
        "// A frozen data snapshot, not program logic: refresh with the script above;",
        "// the route degrades open (absence of a match is 'not listed', never 'safe').",
        "export const MALICIOUS_ADDRESSES: readonly string[] = [",
    ]
    for a in merged:
        lines.append(f'  "{a}",')
    lines.append("];")
    lines.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT}: {len(merged)} addresses (scamsniffer={ss_count}, mew={mew_count}), snapshot {today}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
