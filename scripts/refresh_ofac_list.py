#!/usr/bin/env python3
"""Refresh the vendored OFAC-sanctioned EVM-address snapshot.

Pulls the machine-readable OFAC SDN crypto-address list maintained by
0xB10C (CI-synced from the official U.S. Treasury SDN list) and writes a
TypeScript data module the Worker reads at request time. Keyless, no deps
beyond urllib. The vendored snapshot means the live route has NO runtime
network dependency on a third party — it degrades open and is fast.

Run: python3 -I scripts/refresh_ofac_list.py
"""
import json, re, sys, urllib.request, datetime

SRC = "https://raw.githubusercontent.com/0xB10C/ofac-sanctioned-digital-currency-addresses/lists/sanctioned_addresses_ETH.json"
OUT = "src/data/ofac_sanctioned.ts"
ADDR_RE = re.compile(r"^0x[0-9a-fA-F]{40}$")

def main() -> int:
    req = urllib.request.Request(SRC, headers={"User-Agent": "greyridge-ofac-refresh"})
    with urllib.request.urlopen(req, timeout=30) as r:
        raw = json.load(r)
    addrs = sorted({a.lower() for a in raw if isinstance(a, str) and ADDR_RE.match(a)})
    if not addrs:
        print("refused: source returned zero valid addresses", file=sys.stderr)
        return 1
    today = datetime.date.today().isoformat()
    lines = [
        "// GENERATED by scripts/refresh_ofac_list.py — do not edit by hand.",
        "// Source: OFAC SDN crypto-address list (U.S. Treasury), machine-readable mirror",
        "// 0xB10C/ofac-sanctioned-digital-currency-addresses (CI-synced from the SDN list).",
        f"// Snapshot: {today} · {len(addrs)} EVM addresses.",
        f'export const OFAC_SNAPSHOT_DATE = "{today}";',
        f"export const OFAC_SOURCE_URL = {json.dumps(SRC)};",
        "// Lowercased 0x EVM addresses on the OFAC SDN list. A frozen data snapshot,",
        "// not program logic: refresh with the script above; the route degrades open",
        "// (absence of a match is reported as 'not listed', never asserted 'safe').",
        "export const OFAC_SANCTIONED_ADDRESSES: readonly string[] = [",
    ]
    for a in addrs:
        lines.append(f'  "{a}",')
    lines.append("];")
    lines.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT}: {len(addrs)} addresses, snapshot {today}")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
