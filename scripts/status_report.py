#!/usr/bin/env python3
"""Compute measured uptime/latency per endpoint from data/uptime_samples.jsonl -> docs/STATUS.md (Claims Law artifact).

Also folds the correctness-canary sensor (scripts/uptime_probe.py writes it to
~/.hermes/data/x402-data-api-uptime/latest.json) into the public /status snapshot so a
buyer sees DATA CORRECTNESS, not only availability. HTTP-200 uptime is not correctness: a
geo-blocked upstream returns an empty/hollow 200 that an availability probe never sees.
Every canary has a proven negative control (canary_predicates.py + tests). Degrades OPEN:
if the sensor file is missing/stale the correctness block is omitted (backward-compatible)."""
import json, collections, datetime, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from status_correctness import correctness_block  # noqa: E402

rows=[json.loads(l) for l in open('data/uptime_samples.jsonl') if l.strip()]
by=collections.defaultdict(list)
for r in rows: by[r['ep']].append(r)
ts=sorted(r['t'] for r in rows)
def pct(v,p):
    v=sorted(v); return v[min(len(v)-1,int(round(p*(len(v)-1))))]
out=[f"# Measured status (auto-generated {datetime.datetime.now(datetime.UTC):%Y-%m-%dT%H:%MZ})","",
f"Source: `data/uptime_samples.jsonl`, {len(rows)} samples from {ts[0]} to {ts[-1]}, produced by `scripts/uptime_probe.py` hitting each free `/preview` path. Window is short; treat as a measurement, not an SLA.","",
"| endpoint | samples | success | p50 ms | p95 ms |","|---|---|---|---|---|"]
snap_eps={}
tot_ok=0; tot_n=0
for ep,v in sorted(by.items()):
    ok=sum(1 for r in v if r['ok']); ms=[r['ms'] for r in v if r.get('ms') is not None]
    tot_ok+=ok; tot_n+=len(v)
    out.append(f"| {ep} | {len(v)} | {100*ok/len(v):.1f}% | {pct(ms,.5):.0f} | {pct(ms,.95):.0f} |")
    snap_eps[ep]={"samples":len(v),"success_pct":round(100*ok/len(v),1),
                  "p50_ms":int(round(pct(ms,.5))),"p95_ms":int(round(pct(ms,.95)))}
# Correctness canaries (data correctness, not just HTTP-200 availability). Computed once, used
# for both the crawler-readable markdown and the machine-readable /status JSON below.
_cb=correctness_block()
if _cb is not None:
    out+=["","## Data correctness (canary probes)","",
          f"Method: {_cb['method']}. {_cb['note']} Last checked: {_cb['last_checked']} (fresh: {_cb['fresh']}).","",
          "| route | correctness | guards |","|---|---|---|"]
    for route,chk in _cb["checks"].items():
        out.append(f"| {route} | {chk['status']} | {chk['guards']} |")
open('docs/STATUS.md','w').write("\n".join(out)+"\n"); print("\n".join(out))

# Machine-readable snapshot bundled into the worker, served at GET /status.
# Measured-only (Claims Law): same source as STATUS.md, point-in-time, no SLA.
snapshot={
    "generated_at":f"{datetime.datetime.now(datetime.UTC):%Y-%m-%dT%H:%M:%SZ}",
    "source":"data/uptime_samples.jsonl",
    "window":{"from":ts[0],"to":ts[-1],"samples":len(rows)},
    "overall_success_pct":round(100*tot_ok/tot_n,2) if tot_n else None,
    "note":"5-min free-/preview probe; measurement, not an SLA.",
    "endpoints":snap_eps,
}
if _cb is not None:
    snapshot["correctness"]=_cb
ts_body=("// AUTO-GENERATED by scripts/status_report.py — do not edit by hand.\n"
         "// Measured uptime/latency snapshot served at GET /status (Claims Law artifact).\n"
         "export const STATUS_SNAPSHOT = "+json.dumps(snapshot,indent=2)+" as const;\n")
open('src/status_snapshot.ts','w').write(ts_body)
print("\nwrote src/status_snapshot.ts (overall_success_pct=%s)"%snapshot["overall_success_pct"])
